const YOUTUBE_MAX_BODY_BYTES = 5 * 1024 * 1024;
const YOUTUBE_FETCH_TIMEOUT_MS = 15_000;
const MAX_REDIRECTS = 5;
const YOUTUBE_MIN_CONTENT_CHARS = 20;
const WORDS_PER_PARAGRAPH = 40;
const USER_AGENT = "KairosYT/1.0 (+https://kairos.dev; transcript ingestion bot)";
// The watch page is served as HTML; the timedtext endpoint must be requested as
// XML or YouTube answers with an HTML shell instead of caption cues.
const WATCH_ACCEPT = "text/html,application/xhtml+xml,*/*;q=0.1";
const TIMEDTEXT_ACCEPT = "text/xml,application/xml,*/*;q=0.1";
const VIDEO_ID_RE = /^[A-Za-z0-9_-]{11}$/;
const SENTENCE_END_RE = /[.!?…]$/;

const YOUTUBE_HOSTS = new Set(["youtube.com", "youtu.be"]);

export type YouTubeTranscriptErrorCode =
  | "invalid_url"
  | "unsupported_host"
  | "invalid_video_id"
  | "transcript_unavailable"
  | "transcript_fetch"
  | "transcript_timeout"
  | "transcript_malformed"
  | "transcript_empty"
  | "transcript_blocked"
  | "too_many_redirects"
  | "too_large";

export class YouTubeTranscriptError extends Error {
  constructor(
    public readonly code: YouTubeTranscriptErrorCode,
    message: string,
    options?: { cause?: unknown },
  ) {
    super(message, options);
    this.name = "YouTubeTranscriptError";
  }
}

// User-facing copy for every failure code. Kept next to the codes so the two
// stay in sync and can be asserted in tests without a database.
export function youtubeIngestErrorMessage(code: string): string {
  switch (code) {
    case "invalid_url":
      return "That doesn't look like a valid YouTube video link.";
    case "unsupported_host":
      return "Only youtube.com and youtu.be links are supported.";
    case "invalid_video_id":
      return "That YouTube link does not have a valid video ID.";
    case "transcript_unavailable":
      return "No captions or transcript are available for that video.";
    case "transcript_fetch":
      return "Could not reach YouTube to fetch the transcript.";
    case "transcript_timeout":
      return "YouTube did not respond in time.";
    case "transcript_malformed":
      return "The transcript returned by YouTube could not be read.";
    case "transcript_empty":
      return "That video has no usable transcribed text.";
    case "transcript_blocked":
      return "YouTube did not return the transcript for that video. This is usually temporary — please try again in a moment.";
    case "too_many_redirects":
      return "That video link redirects too many times.";
    case "too_large":
      return "That video's transcript is too large to ingest.";
    default:
      return "Could not fetch that video's transcript.";
  }
}

export interface YouTubeTranscript {
  videoId: string;
  canonicalUrl: string;
  title: string;
  languageCode: string | null;
  autoGenerated: boolean;
  cueCount: number;
  text: string;
}

export interface FetchYoutubeOptions {
  resolveHost?: ResolveHostFn;
  httpGet?: HttpGetFn;
  timeoutMs?: number;
  maxResponseBytes?: number;
  maxRedirects?: number;
}

export function parseYouTubeUrl(rawUrl: string): { videoId: string; canonicalUrl: string } {
  let url: URL;
  try {
    url = new URL(rawUrl.trim());
  } catch {
    throw new YouTubeTranscriptError("invalid_url", "YouTube URL could not be parsed");
  }
  if (url.protocol !== "http:" && url.protocol !== "https:") {
    throw new YouTubeTranscriptError("invalid_url", `Unsupported protocol: ${url.protocol}`);
  }

  // Host allowlist comes first: "youtube.com@evil.com" is an evil.com link,
  // not a credentials bug.
  const baseHost = stripHostPrefix(url.hostname.toLowerCase());
  if (!YOUTUBE_HOSTS.has(baseHost)) {
    throw new YouTubeTranscriptError("unsupported_host", `Not a YouTube host: ${url.hostname}`);
  }

  if (url.username || url.password) {
    throw new YouTubeTranscriptError("invalid_url", "URLs with embedded credentials are not allowed");
  }

  let videoId: string | null = null;
  if (baseHost === "youtu.be") {
    videoId = url.pathname.split("/")[1] ?? null;
  } else if (url.searchParams.get("v")) {
    videoId = url.searchParams.get("v");
  } else {
    const segment = url.pathname.split("/")[2] ?? null;
    if (url.pathname.startsWith("/shorts/") || url.pathname.startsWith("/embed/")) videoId = segment;
  }

  if (!videoId || !VIDEO_ID_RE.test(videoId)) {
    throw new YouTubeTranscriptError("invalid_video_id", "YouTube link has no valid video ID");
  }
  return { videoId, canonicalUrl: `https://www.youtube.com/watch?v=${videoId}` };
}

function stripHostPrefix(hostname: string): string {
  return hostname.replace(/^www\./i, "").replace(/^m\./i, "");
}

function isYoutubeHost(hostname: string): boolean {
  return YOUTUBE_HOSTS.has(stripHostPrefix(hostname.toLowerCase()));
}

function isRedirectStatus(status: number): boolean {
  return status === 301 || status === 302 || status === 303 || status === 307 || status === 308;
}

function mapUrlError(err: unknown): YouTubeTranscriptError {
  if (err instanceof YouTubeTranscriptError) return err;
  if (err instanceof UrlSourceError) {
    switch (err.code) {
      case "too_large":
        return new YouTubeTranscriptError("too_large", err.message, { cause: err });
      case "timeout":
        return new YouTubeTranscriptError("transcript_timeout", err.message, { cause: err });
      case "too_many_redirects":
        return new YouTubeTranscriptError("too_many_redirects", err.message, { cause: err });
      case "blocked":
        return new YouTubeTranscriptError("transcript_fetch", err.message, { cause: err });
      case "invalid_url":
        return new YouTubeTranscriptError("transcript_malformed", err.message, { cause: err });
      default:
        return new YouTubeTranscriptError("transcript_fetch", err.message, { cause: err });
    }
  }
  return new YouTubeTranscriptError(
    "transcript_fetch",
    err instanceof Error ? err.message : String(err),
    { cause: err },
  );
}

// Fixed, allowlisted endpoint host only. No generic fetch-any-URL path for
// YouTube; every hop is host-allowlisted AND resolves to a public address.
async function fetchYoutubeText(url: string, opts: Required<FetchYoutubeOptions>, accept: string): Promise<string> {
  let current = loadTarget(url);
  for (let hop = 0; ; hop++) {
    if (!isYoutubeHost(current.hostname)) {
      throw new YouTubeTranscriptError("unsupported_host", `Redirect to non-YouTube host: ${current.hostname}`);
    }
    await assertPublicHost(current.hostname, opts.resolveHost);

    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), opts.timeoutMs);
    let response: HttpGetResult;
    try {
      response = await opts.httpGet(current.href, {
        signal: controller.signal,
        headers: {
          "user-agent": USER_AGENT,
          accept,
          "accept-language": "en",
        },
      });
      if (isRedirectStatus(response.status)) {
        if (hop >= opts.maxRedirects) {
          throw new YouTubeTranscriptError("too_many_redirects", `More than ${opts.maxRedirects} redirects`);
        }
        const location = response.headers.get("location");
        if (!location) {
          throw new YouTubeTranscriptError("transcript_fetch", "Redirect response had no Location header");
        }
        try {
          current = loadTarget(new URL(location, current).href);
        } catch (err) {
          throw mapUrlError(err);
        }
        continue;
      }

      if (response.status !== 200) {
        // A refusal is not "could not reach": 429 (rate limited) and 403
        // (blocked) mean YouTube answered and declined, which is usually
        // temporary. Keep that distinct from a transport-level failure.
        if (response.status === 429 || response.status === 403) {
          throw new YouTubeTranscriptError("transcript_blocked", `YouTube refused the transcript request (HTTP ${response.status})`);
        }
        throw new YouTubeTranscriptError("transcript_fetch", `HTTP ${response.status}`);
      }

      return await readBoundedText(response.body, opts.maxResponseBytes);
    } catch (err) {
      if (err instanceof YouTubeTranscriptError) throw err;
      if (err instanceof UrlSourceError) throw mapUrlError(err);
      if (err instanceof Error && err.name === "AbortError") {
        throw new YouTubeTranscriptError("transcript_timeout", `Request timed out after ${opts.timeoutMs}ms`, { cause: err });
      }
      throw new YouTubeTranscriptError("transcript_fetch", `Network error while fetching ${current.href}`, { cause: err });
    } finally {
      clearTimeout(timer);
    }
  }
}

interface CaptionTrack {
  baseUrl?: string;
  languageCode?: string;
  kind?: string;
  name?: { simpleText?: string };
}

interface PlayerResponseLike {
  playabilityStatus?: {
    status?: string;
    reason?: string;
  };
  captions?: {
    playerCaptionsTracklistRenderer?: {
      captionTracks?: CaptionTrack[];
    };
  };
  videoDetails?: {
    videoId?: string;
    title?: string;
  };
}

// The watch page embeds its player payload as an inline JS object. The legacy
// get_video_info endpoint that used to expose the same payload now returns HTTP
// 410 (retired by YouTube), so we read the payload straight from the watch page.
function extractPlayerResponse(html: string): PlayerResponseLike {
  const assignment = /ytInitialPlayerResponse"?\]?\s*=\s*\{/.exec(html);
  if (assignment?.index === undefined) {
    throw new YouTubeTranscriptError("transcript_unavailable", "watch page did not include a player response");
  }
  const start = assignment.index + assignment[0].length - 1;
  let parsed: unknown;
  try {
    parsed = JSON.parse(extractBalancedObject(html, start));
  } catch (err) {
    if (err instanceof YouTubeTranscriptError) throw err;
    throw new YouTubeTranscriptError("transcript_malformed", "player response was not valid JSON", { cause: err });
  }
  const player = parsed as PlayerResponseLike;
  const status = player.playabilityStatus?.status;
  if (status && status !== "OK") {
    throw new YouTubeTranscriptError("transcript_unavailable", `video is not playable (${status})`);
  }
  return player;
}

// Slice the balanced JSON object starting at `start` (which must be "{"), while
// ignoring braces inside string literals/escapes.
function extractBalancedObject(text: string, start: number): string {
  let depth = 0;
  let inString = false;
  let escaped = false;
  for (let i = start; i < text.length; i++) {
    const ch = text[i];
    if (inString) {
      if (escaped) escaped = false;
      else if (ch === "\\") escaped = true;
      else if (ch === '"') inString = false;
      continue;
    }
    if (ch === '"') inString = true;
    else if (ch === "{") depth++;
    else if (ch === "}") {
      depth--;
      if (depth === 0) return text.slice(start, i + 1);
    }
  }
  throw new YouTubeTranscriptError("transcript_malformed", "player response JSON was incomplete");
}

function selectCaptionTrack(player: PlayerResponseLike): CaptionTrack {
  const tracks = player.captions?.playerCaptionsTracklistRenderer?.captionTracks;
  if (!tracks || tracks.length === 0) {
    throw new YouTubeTranscriptError("transcript_unavailable", "no caption tracks available");
  }
  // Manual (kind !== "asr") is preferred over auto-generated; within the chosen
  // pool, an English track wins; otherwise the first usable track is used.
  const manual = tracks.filter((t) => !t.kind || t.kind !== "asr");
  const pool = manual.length > 0 ? manual : tracks;
  const english = pool.find((t) => (t.languageCode || "").toLowerCase().startsWith("en"));
  const track = english ?? pool[0];
  if (!track?.baseUrl) {
    throw new YouTubeTranscriptError("transcript_unavailable", "selected caption track had no baseUrl");
  }
  return track;
}

interface CaptionCue {
  start: number;
  duration: number;
  text: string;
}

function parseTimedText(body: string): CaptionCue[] {
  // A page body (or JSON blob) is not caption XML even if it contains <text>.
  if (!/<text\b/i.test(body) && !/<transcript\b/i.test(body)) {
    throw new YouTubeTranscriptError("transcript_malformed", "timedtext response is not caption XML");
  }
  const cues: CaptionCue[] = [];
  for (const match of body.matchAll(/<text\b([^>]*)>([\s\S]*?)<\/text>/gi)) {
    const attrs = match[1] ?? "";
    const start = parseFloat(/start="([^"]*)"/i.exec(attrs)?.[1] ?? "");
    const duration = parseFloat(/dur="([^"]*)"/i.exec(attrs)?.[1] ?? "0");
    const text = normalizeCueText(match[2] ?? "");
    if (!text) continue;
    cues.push({
      start: Number.isFinite(start) ? start : 0,
      duration: Number.isFinite(duration) ? duration : 0,
      text,
    });
  }
  return cues;
}

function normalizeCueText(raw: string): string {
  const plain = raw.replace(/<[^>]+>/g, "");
  return decodeEntities(plain).replace(/\s+/g, " ").trim();
}

function buildTranscriptText(cues: CaptionCue[]): string {
  const paragraphs: string[] = [];
  let words: string[] = [];
  let count = 0;
  const flush = () => {
    if (words.length > 0) {
      paragraphs.push(words.join(" "));
      words = [];
      count = 0;
    }
  };
  for (const cue of cues) {
    for (const word of cue.text.split(" ")) {
      words.push(word);
      count++;
      if (count >= WORDS_PER_PARAGRAPH || SENTENCE_END_RE.test(word)) flush();
    }
  }
  flush();
  return paragraphs.join("\n\n");
}

export async function fetchYouTubeTranscript(rawUrl: string, opts: FetchYoutubeOptions = {}): Promise<YouTubeTranscript> {
  const { videoId } = parseYouTubeUrl(rawUrl);
  const fullOpts: Required<FetchYoutubeOptions> = {
    resolveHost: opts.resolveHost ?? defaultResolveHost,
    httpGet: opts.httpGet ?? defaultHttpGet,
    timeoutMs: opts.timeoutMs ?? YOUTUBE_FETCH_TIMEOUT_MS,
    maxResponseBytes: opts.maxResponseBytes ?? YOUTUBE_MAX_BODY_BYTES,
    maxRedirects: opts.maxRedirects ?? MAX_REDIRECTS,
  };

  const watchUrl = `https://www.youtube.com/watch?v=${videoId}&hl=en`;
  const player = extractPlayerResponse(await fetchYoutubeText(watchUrl, fullOpts, WATCH_ACCEPT));
  const track = selectCaptionTrack(player);

  const baseUrl = track.baseUrl;
  if (!baseUrl) {
    throw new YouTubeTranscriptError("transcript_unavailable", "selected caption track had no baseUrl");
  }

  let timedTextUrl: string;
  try {
    timedTextUrl = new URL(baseUrl, "https://www.youtube.com").href;
  } catch (err) {
    throw new YouTubeTranscriptError("transcript_malformed", "caption track baseUrl was invalid", { cause: err });
  }
  const timedTextBody = await fetchYoutubeText(timedTextUrl, fullOpts, TIMEDTEXT_ACCEPT);
  if (timedTextBody.trim().length === 0) {
    // A caption track was offered but YouTube served an empty body — a temporary
    // throttle or server-side restriction, not "this video has no captions".
    throw new YouTubeTranscriptError(
      "transcript_blocked",
      "YouTube returned an empty transcript response for a video that has captions",
    );
  }

  const cues = parseTimedText(timedTextBody);
  if (cues.length === 0) {
    throw new YouTubeTranscriptError("transcript_empty", "timedtext contained no cues");
  }
  const text = buildTranscriptText(cues);
  if (text.trim().length < YOUTUBE_MIN_CONTENT_CHARS) {
    throw new YouTubeTranscriptError("transcript_empty", "transcribed text is too short to ingest");
  }

  return {
    videoId,
    canonicalUrl: `https://www.youtube.com/watch?v=${videoId}`,
    title: player.videoDetails?.title?.trim() || "",
    languageCode: track.languageCode || null,
    autoGenerated: track.kind === "asr",
    cueCount: cues.length,
    text,
  };
}

export function buildYouTubeDocumentData(params: {
  kbId: string;
  userId: string;
  sourceUrl: string;
  videoId: string;
  title: string;
  languageCode: string | null;
  autoGenerated: boolean;
  cueCount: number;
  text: string;
}): Prisma.DocumentUncheckedCreateInput {
  const buffer = Buffer.from(params.text, "utf8");
  const name = (params.title || `YouTube ${params.videoId}`).slice(0, 255);
  return {
    name,
    fileType: "txt",
    size: buffer.byteLength,
    fileHash: urlDocumentFileHash(params.text),
    sourceType: "YOUTUBE",
    sourceUrl: params.sourceUrl,
    status: "STORED",
    storageProvider: null,
    storageKey: null,
    storageUrl: null,
    knowledgeBaseId: params.kbId,
    uploadedById: params.userId,
    metadata: {
      mimeType: "text/plain",
      source: "youtube",
      videoId: params.videoId,
      title: params.title,
      languageCode: params.languageCode,
      autoGenerated: params.autoGenerated,
      cueCount: params.cueCount,
    },
  };
}